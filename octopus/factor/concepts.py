_CODE_RE = re.compile(r"^(\d{6})$")


def to_yahoo_symbol(code: str) -> str:
    """A 股代码 -> Yahoo Finance 代码（国外免费数据源）。"""
    code = (code or "").strip()
    m = _CODE_RE.match(code)
    if not m:
        raise ValueError(f"不是合法的 A 股代码：{code!r}")
    if code[0] in "69":
        return f"{code}.SS"      # 沪市主板/科创板
    if code[0] in "023":
        return f"{code}.SZ"      # 深市主板/创业板
    if code[0] in "48":
        return f"{code}.BJ"      # 北交所
    raise ValueError(f"无法识别市场前缀：{code!r}")


def to_secid(code: str) -> str:
    """A 股代码 -> 东财 secid（市场.代码，1=沪 0=深）。"""
    code = (code or "").strip()
    if code[0] in "69":
        return f"1.{code}"
    return f"0.{code}"


def secid_to_yahoo_symbol(secid: str) -> str:
    """东财 secid（或代码/Yahoo 符号）-> Yahoo Finance 代码。

    必须保留市场前缀做消歧：`1.000001` 是上证指数（.SS），
    `0.000001` 是平安银行（.SZ）—— 只看数字会撞车。
    """
    secid = (secid or "").strip()
    if "." not in secid:
        return to_yahoo_symbol(secid)
    left, right = secid.rsplit(".", 1)
    if right.upper() in ("SS", "SZ", "BJ"):
        return secid                        # 已是 Yahoo 符号
    if left == "1":
        return f"{right}.SS"                # 沪市（含上证指数 000001.SS）
    if left == "0":
        return f"{right}.SZ"                # 深市（含深证成指/创业板指）
    if left == "2":
        return f"{right}.BJ"                # 北交所
    return to_yahoo_symbol(right)


def secid_to_code(secid: str) -> str:
    """任意标识 -> 6 位代码。

    兼容三种写法：东财 secid（"1.600519"）、Yahoo 符号（"600519.SS"）、
    裸代码（"600519"）。
    """
    code = (secid or "").strip()
    if "." in code:
        left, right = code.rsplit(".", 1)
        if right.upper() in ("SS", "SZ", "BJ"):   # Yahoo 风格：市场后缀在右边
            return left
        return right                                # 东财风格：市场前缀在左边
    return code
